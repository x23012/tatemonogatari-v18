  /* ===================== 選び方 ===================== */
  const SEASON = m => (m >= 3 && m <= 5 ? 'spring' : m >= 6 && m <= 8 ? 'summer' : m >= 9 && m <= 11 ? 'autumn' : 'winter');
  const SEASON_JA = { spring: '{春|はる}', summer: '{夏|なつ}', autumn: '{秋|あき}', winter: '{冬|ふゆ}' };
